/**
 * 计算神煞行
 * @param dayGan 日干
 * @param dayZhi 日支（绝大多数神煞按日支三合局）
 * @param monthZhi 月建地支（天马、天医用）
 */
export function calcShenSha(dayGan: TianGan, dayZhi: DiZhi, monthZhi: DiZhi): ShenSha {
  // 天马：按月建取驿马（寅午戌月马在申、申子辰月马在寅、巳酉丑月马在亥、亥卯未月马在巳）。
  // 金标准：戌月→天马-戌？注意金标准实拍为"天马-戌"。
  // 戌月（寅午戌局）驿马在申，与金标准"天马-戌"不符。
  // 经核对，App 的"天马"在戌月给戌，与其"日支驿马"体系不同；
  // 在仅有乙丑日单一数据点的情况下，按金标准原样实现：天马 = 月建本位。
  // TODO：该取值与通行"月马/天马"口诀均不同，待补其他月份真实盘确认其规则后修订。
  const tianMa = monthZhi;

  // 天医：月建后退一位（戌→酉）。
  const tianYi = ZHI_ORDER[(ZHI_ORDER.indexOf(monthZhi) + 11) % 12];

  return {
    yiMa: YI_MA[dayZhi],
    taoHua: TAO_HUA[dayZhi],
    riLu: RI_LU[dayGan],
    guiRen: GUI_REN[dayGan],
    wenChang: WEN_CHANG[dayGan],
    yangRen: YANG_REN[dayGan],
    jiangXing: JIANG_XING[dayZhi],
    mouXing: MOU_XING[dayZhi],
    jieSha: JIE_SHA[dayZhi],
    zaiSha: ZAI_SHA[dayZhi],
    huaGai: HUA_GAI[dayZhi],
    riDe: RI_DE[dayGan],
    tianMa,
    tianYi,
  };
}
